def _service(
    root: Path,
    fake: _FakeGitHub,
    *,
    repair: _FakeRepairSession | None = None,
    now: int = 2_000_000,
    interface: GitHubApprovalInterface = GitHubApprovalInterface.CLI,
    expected_principal_login: str | None = None,
) -> tuple[GitHubPublicationService, GitHubPublicationStore]:
    store = _store(root)
    transport = GitHubTransport("github_pat_EXPLICIT", sender=fake)
    manager = None if repair is None else _FakeRepairManager(repair)
    service = GitHubPublicationService(
        transport=transport,
        store=store,
        interface=interface,
        repair_manager=manager,
        clock=lambda: now,
        expected_principal_login=expected_principal_login,
    )
    return service, store


def test_expected_action_principal_must_match_token_for_new_and_final_publication(
    state_root: Path,
) -> None:
    fake = _FakeGitHub()
    mismatched, store = _service(
        state_root,
        fake,
        interface=GitHubApprovalInterface.ACTION,
        expected_principal_login="workflow-actor",
    )
    proposal = _check_proposal()
    store.record_proposal(proposal)

    with pytest.raises(GitHubPublicationError) as rejected:
        mismatched.publish_check(
            proposal.proposal_sha256,
            confirmation=GITHUB_CHECK_CONFIRMATION,
        )

    assert rejected.value.code == GitHubPublicationErrorCode.PRINCIPAL_MISMATCH.value
    assert rejected.value.stage is GitHubPublicationStage.PRINCIPAL
    assert fake.write_requests == []

    matched, _ = _service(
        state_root,
        fake,
        interface=GitHubApprovalInterface.ACTION,
        expected_principal_login="reviewer",
    )
    result = matched.publish_check(
        proposal.proposal_sha256,
        confirmation=GITHUB_CHECK_CONFIRMATION,
    )
    assert result.state is GitHubPublicationState.CHECK_PUBLISHED
    write_count = len(fake.write_requests)

    revalidation_mismatch, _ = _service(
        state_root,
        fake,
        interface=GitHubApprovalInterface.ACTION,
        expected_principal_login="workflow-actor",
    )
    with pytest.raises(GitHubPublicationError) as revalidation:
        revalidation_mismatch.publish_check(
            proposal.proposal_sha256,
            confirmation=GITHUB_CHECK_CONFIRMATION,
        )
    assert revalidation.value.code == GitHubPublicationErrorCode.PRINCIPAL_MISMATCH.value
    assert len(fake.write_requests) == write_count


