def _git_blob_oid(content: bytes) -> str:
    header = f"blob {len(content)}\0".encode("ascii")
    return hashlib.sha1(header + content, usedforsecurity=False).hexdigest()


_BLOB_OID = _git_blob_oid(_BLOB_CONTENT)


def _fixed_commit_oid() -> str:
    identity = f"{REPAIR_PUBLICATION_AUTHOR_NAME} <{REPAIR_PUBLICATION_AUTHOR_EMAIL}> 0 +0000"
    content = (
        f"tree {_TREE_OID}\n"
        f"parent {_HEAD_OID}\n"
        f"author {identity}\n"
        f"committer {identity}\n"
        "\n"
        f"{REPAIR_PUBLICATION_COMMIT_MESSAGE}"
    ).encode()
    header = f"commit {len(content)}\0".encode("ascii")
    return hashlib.sha1(header + content, usedforsecurity=False).hexdigest()


_COMMIT_OID = _fixed_commit_oid()


def _review(*, annotation_count: int = 0) -> ProductReviewResult:
    findings: tuple[ProductFinding, ...] = ()
    if annotation_count:
        references = tuple(
            ProductReference(
                path="src/app.py",
                side=EvidenceSide.NEW,
                oid=_HEAD_OID,
                start_line=line,
                end_line=line,
                repair_target_id=None,
            )
            for line in range(1, annotation_count + 1)
        )
        findings = (
            ProductFinding(
                source=FindingSource.AGENT,
                rule_id="agent_reasoning",
                category=FindingCategory.SECURITY,
                severity=FindingSeverity.LOW,
                title="Review finding",
                message="Review this line.",
                remediation="Keep the safe behavior.",
                references=references,
            ),
        )
    return ProductReviewResult(
        schema_version=1,
        repository_alias="repository",
        object_format="sha1",
        base_ref="base-input",
        head_ref="head-input",
        base_oid=_BASE_OID,
        head_oid=_HEAD_OID,
        merge_base_oid=_BASE_OID,
        review_profile="deterministic",
        provider=None,
        model=None,
        evidence_sha256="a" * 64,
        deterministic_review_sha256="b" * 64,
        review_sha256="c" * 64,
        findings=findings,
        finding_count=len(findings),
        highest_severity=None if not findings else FindingSeverity.LOW,
        conclusion=ProductConclusion.SUCCESS,
    )


def _validated_repair() -> tuple[RepairSnapshot, RepairPreview]:
    prompt = RepairPromptIdentity("repoguard_repair", 1, "1" * 64, "2" * 64, "3" * 64)
    context = RepairContextSummary(
        RepairContextOutcome.NOT_REQUESTED,
        None,
        None,
        0,
        0,
        0,
        None,
        None,
    )
    candidate = RepairCandidate(
        1,
        _CANDIDATE_ID,
        "d" * 64,
        prompt,
        context,
        "e" * 64,
        _TREE_OID,
        _COMMIT_OID,
        ("src/app.py",),
        1,
        0,
        0,
        0,
    )
    command = ValidationCommandResult(
        0,
        0,
        None,
        False,
        1,
        "f" * 64,
        0,
        False,
        "0" * 64,
        0,
        False,
    )
    validation = RepairValidation(
        1,
        _VALIDATION_SHA256,
        _CANDIDATE_ID,
        "1" * 64,
        "2" * 64,
        f"sha256:{'3' * 64}",
        1,
        2,
        True,
        None,
        (command,),
        1,
        False,
        0,
        1,
        1,
        True,
    )
    snapshot = RepairSnapshot(
        1,
        _SESSION_ID,
        RepairState.VALIDATED,
        "d" * 64,
        1,
        2,
        1,
        ("src/app.py",),
        candidate,
        validation,
        None,
        None,
        None,
        None,
        False,
    )
    preview = RepairPreview(
        1,
        _SESSION_ID,
        RepairState.VALIDATED,
        _CANDIDATE_ID,
        _VALIDATION_SHA256,
        ("src/app.py",),
        "diff --git a/src/app.py b/src/app.py\n",
        REPAIR_APPROVAL_CONFIRMATION,
    )
    return snapshot, preview


