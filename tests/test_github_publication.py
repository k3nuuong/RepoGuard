def _json_response(status: int, value: object) -> GitHubWireResponse:
    return GitHubWireResponse(
        status=status,
        headers=(("Content-Type", "application/json"),),
        body=json.dumps(value, separators=(",", ":")).encode(),
    )


class _FakeGitHub:
    def __init__(self) -> None:
        self.actor_id = 42
        self.actor_login = "reviewer"
        self.permission = "write"
        self.repository_is_fork = False
        self.source_state = "open"
        self.source_head_oid = _HEAD_OID
        self.requests: list[GitHubWireRequest] = []
        self.check: dict[str, object] | None = None
        self.check_annotations: list[dict[str, object]] = []
        self.ambiguous_check_create = False
        self.ambiguous_check_append = False
        self.ambiguous_check_final = False
        self.blobs: set[str] = set()
        self.tree_exists = False
        self.commit_exists = False
        self.ambiguous_blob = False
        self.ambiguous_tree = False
        self.ambiguous_commit = False
        self.ambiguous_branch = False
        self.ambiguous_pull_request = False
        self.branch_oid: str | None = None
        self.replacement: dict[str, object] | None = None
        self.fail_pull_request = False

    @property
    def write_requests(self) -> list[GitHubWireRequest]:
        return [item for item in self.requests if item.method.value in {"POST", "PATCH"}]

    def send(self, request: GitHubWireRequest) -> GitHubWireResponse:
        self.requests.append(request)
        target = request.target
        body = (
            {}
            if request.body is None
            else cast(dict[str, object], json.loads(request.body.decode()))
        )
        if request.method.value == "GET" and target == "/user":
            return _json_response(
                200,
                {"id": self.actor_id, "login": self.actor_login},
            )
        if target == (f"/repos/owner/repository/collaborators/{self.actor_login}/permission"):
            return _json_response(
                200,
                {
                    "permission": self.permission,
                    "user": {"id": self.actor_id, "login": self.actor_login},
                },
            )
        if target == "/repos/owner/repository":
            return _json_response(
                200,
                {
                    "id": _REPOSITORY_ID,
                    "full_name": _REPOSITORY_FULL_NAME,
                    "fork": self.repository_is_fork,
                },
            )
        if target == "/repos/owner/repository/pulls/7":
            return _json_response(200, self._source_pull_request())
        if "/commits/" in target and "/check-runs?" in target:
            values = [] if self.check is None else [self.check]
            return _json_response(200, {"total_count": len(values), "check_runs": values})
        if request.method.value == "POST" and target.endswith("/check-runs"):
            self.check_annotations.extend(
                cast(
                    list[dict[str, object]],
                    cast(dict[str, object], body["output"])["annotations"],
                )
            )
            self.check = self._check_run(
                external_id=cast(str, body["external_id"]),
                status="in_progress",
                conclusion=None,
                summary=cast(str, cast(dict[str, object], body["output"])["summary"]),
            )
            if self.ambiguous_check_create:
                self.ambiguous_check_create = False
                raise TimeoutError
            return _json_response(201, self.check)
        if "/check-runs/17/annotations?" in target:
            query = target.split("?", 1)[1]
            page = int(query.rsplit("=", 1)[1])
            start = (page - 1) * 100
            return _json_response(200, self.check_annotations[start : start + 100])
        if target.endswith("/check-runs/17") and request.method.value == "GET":
            assert self.check is not None
            return _json_response(200, self.check)
        if target.endswith("/check-runs/17") and request.method.value == "PATCH":
            assert self.check is not None
            output = cast(dict[str, object], body["output"])
            annotations = cast(list[dict[str, object]], output.get("annotations", []))
            self.check_annotations.extend(annotations)
            status = cast(str, body["status"])
            conclusion = cast(str | None, body.get("conclusion"))
            self.check = self._check_run(
                external_id=cast(str, self.check["external_id"]),
                status=status,
                conclusion=conclusion,
                summary=cast(str, output["summary"]),
            )
            if status == "in_progress" and self.ambiguous_check_append:
                self.ambiguous_check_append = False
                raise TimeoutError
            if status == "completed" and self.ambiguous_check_final:
                self.ambiguous_check_final = False
                raise TimeoutError
            return _json_response(200, self.check)
        if target == f"/repos/owner/repository/git/commits/{_HEAD_OID}":
            return _json_response(
                200,
                {"sha": _HEAD_OID, "tree": {"sha": _PARENT_TREE_OID}, "parents": []},
            )
        if target == f"/repos/owner/repository/git/blobs/{_BLOB_OID}":
            if _BLOB_OID not in self.blobs:
                return _json_response(404, {"message": "not found"})
            return _json_response(
                200,
                {
                    "sha": _BLOB_OID,
                    "size": len(_BLOB_CONTENT),
                    "encoding": "base64",
                    "content": base64.b64encode(_BLOB_CONTENT).decode(),
                },
            )
        if request.method.value == "POST" and target.endswith("/git/blobs"):
            content = base64.b64decode(cast(str, body["content"]), validate=True)
            oid = _git_blob_oid(content)
            self.blobs.add(oid)
            if self.ambiguous_blob:
                self.ambiguous_blob = False
                raise TimeoutError
            return _json_response(201, {"sha": oid})
        if target == f"/repos/owner/repository/git/trees/{_TREE_OID}":
            if not self.tree_exists:
                return _json_response(404, {"message": "not found"})
            return _json_response(200, {"sha": _TREE_OID})
        if request.method.value == "POST" and target.endswith("/git/trees"):
            assert body["base_tree"] == _PARENT_TREE_OID
            self.tree_exists = True
            if self.ambiguous_tree:
                self.ambiguous_tree = False
                raise TimeoutError
            return _json_response(201, {"sha": _TREE_OID})
        if target == f"/repos/owner/repository/git/commits/{_COMMIT_OID}":
            if not self.commit_exists:
                return _json_response(404, {"message": "not found"})
            return _json_response(
                200,
                {
                    "sha": _COMMIT_OID,
                    "tree": {"sha": _TREE_OID},
                    "parents": [{"sha": _HEAD_OID}],
                },
            )
        if request.method.value == "POST" and target.endswith("/git/commits"):
            assert body["tree"] == _TREE_OID
            assert body["parents"] == [_HEAD_OID]
            self.commit_exists = True
            if self.ambiguous_commit:
                self.ambiguous_commit = False
                raise TimeoutError
            return _json_response(
                201,
                {"sha": _COMMIT_OID, "tree": {"sha": _TREE_OID}},
            )
        if "/git/ref/heads/repoguard/repairs/" in target:
            if self.branch_oid is None:
                return _json_response(404, {"message": "not found"})
            return _json_response(200, self._branch())
        if request.method.value == "POST" and target.endswith("/git/refs"):
            assert body == {"ref": _BRANCH_REF, "sha": _COMMIT_OID}
            if self.branch_oid is not None:
                return _json_response(422, {"message": "exists"})
            self.branch_oid = _COMMIT_OID
            if self.ambiguous_branch:
                self.ambiguous_branch = False
                raise TimeoutError
            return _json_response(201, self._branch())
        if "/pulls?state=all" in target:
            values = [] if self.replacement is None else [self.replacement]
            return _json_response(200, values)
        if request.method.value == "POST" and target.endswith("/pulls"):
            if self.fail_pull_request:
                return _json_response(500, {"message": "unavailable"})
            self.replacement = self._replacement_pull_request(body)
            if self.ambiguous_pull_request:
                self.ambiguous_pull_request = False
                raise TimeoutError
            return _json_response(201, self.replacement)
        if target == "/repos/owner/repository/pulls/8":
            assert self.replacement is not None
            return _json_response(200, self.replacement)
        raise AssertionError(f"unexpected request: {request.method.value} {target}")

    def _source_pull_request(self) -> dict[str, object]:
        repository = {"id": _REPOSITORY_ID, "full_name": _REPOSITORY_FULL_NAME}
        return {
            "id": 700,
            "number": 7,
            "state": self.source_state,
            "base": {"ref": "main", "sha": _BASE_OID, "repo": repository},
            "head": {"ref": "feature", "sha": self.source_head_oid, "repo": repository},
        }

    def _check_run(
        self,
        *,
        external_id: str,
        status: str,
        conclusion: str | None,
        summary: str,
    ) -> dict[str, object]:
        return {
            "id": 17,
            "node_id": "CR_node",
            "name": "RepoGuard review",
            "head_sha": _HEAD_OID,
            "external_id": external_id,
            "status": status,
            "conclusion": conclusion,
            "html_url": "https://github.com/owner/repository/runs/17",
            "output": {
                "title": "RepoGuard review",
                "summary": summary,
                "annotations_count": len(self.check_annotations),
            },
        }

    def _branch(self) -> dict[str, object]:
        assert self.branch_oid is not None
        return {
            "ref": _BRANCH_REF,
            "object": {"type": "commit", "sha": self.branch_oid},
        }

    def _replacement_pull_request(self, body: dict[str, object]) -> dict[str, object]:
        repository = {"id": _REPOSITORY_ID, "full_name": _REPOSITORY_FULL_NAME}
        return {
            "id": 800,
            "number": 8,
            "node_id": "PR_node",
            "html_url": "https://github.com/owner/repository/pull/8",
            "draft": body["draft"],
            "state": "open",
            "title": body["title"],
            "body": body["body"],
            "base": {"ref": body["base"], "repo": repository},
            "head": {"ref": body["head"], "repo": repository},
        }


