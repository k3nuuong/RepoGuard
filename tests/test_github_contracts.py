@pytest.mark.parametrize(
    "mismatch",
    [
        "snapshot_state",
        "session",
        "candidate",
        "validation",
        "paths",
        "allowlist",
        "local_approval",
        "commit",
        "head",
    ],
)
def test_repair_builder_rejects_m5_identity_mismatches(mismatch: str) -> None:
    snapshot, preview = _validated_repair()
    review = _review()
    if mismatch == "snapshot_state":
        snapshot = replace(snapshot, state=RepairState.VALIDATING)
    elif mismatch == "session":
        preview = replace(preview, session_id="d" * 64)
    elif mismatch == "candidate":
        preview = replace(preview, candidate_id="d" * 64)
    elif mismatch == "validation":
        preview = replace(preview, validation_sha256="d" * 64)
    elif mismatch == "paths":
        preview = replace(preview, changed_paths=("other.py",))
    elif mismatch == "allowlist":
        snapshot = replace(snapshot, allowed_paths=("other.py",))
    elif mismatch == "local_approval":
        snapshot = replace(
            snapshot,
            approval=RepairApproval(
                1,
                "d" * 64,
                _CANDIDATE_ID,
                _VALIDATION_SHA256,
                "uid:1000",
                REPAIR_APPROVAL_CONFIRMATION,
                3,
            ),
        )
    elif mismatch == "commit":
        assert snapshot.candidate is not None
        snapshot = replace(
            snapshot,
            candidate=replace(snapshot.candidate, commit_oid="f" * 40),
        )
    else:
        review = _review(head_oid="f" * 40, review_sha256="1" * 64)

    with pytest.raises(ValueError, match="repair proposal"):
        _repair_proposal(review=review, snapshot=snapshot, preview=preview)


