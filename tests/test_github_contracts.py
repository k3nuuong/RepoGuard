def test_check_builder_derives_plain_text_summary_and_stable_annotations() -> None:
    critical = _finding(
        severity=FindingSeverity.CRITICAL,
        title="@octocat <details> [click](https://evil.invalid) `code` " + "[" * 300,
        message="# heading **bold** @team",
        remediation="Never run <script>.",
        references=(_reference(path="z.py", start_line=9, end_line=10, target=None),),
        source=FindingSource.AGENT,
    )
    high = _finding(
        severity=FindingSeverity.HIGH,
        references=(_reference(path="a.py", start_line=1, end_line=1, target=None),),
        source=FindingSource.AGENT,
    )
    medium = _finding(
        severity=FindingSeverity.MEDIUM,
        references=(_reference(path="b.py", start_line=2, end_line=2, target=None),),
        source=FindingSource.AGENT,
    )
    old_only = _finding(
        severity=FindingSeverity.CRITICAL,
        references=(
            _reference(
                path="old.py",
                side=EvidenceSide.OLD,
                start_line=3,
                end_line=3,
                target=None,
            ),
        ),
        source=FindingSource.AGENT,
    )
    proposal = _check_proposal(review=_review(findings=(high, medium, critical, old_only)))
    payload = proposal.payload
    annotations = cast(list[dict[str, object]], payload["annotations"])

    assert [annotation["path"] for annotation in annotations] == ["z.py", "a.py", "b.py"]
    assert [annotation["annotation_level"] for annotation in annotations] == [
        "failure",
        "failure",
        "warning",
    ]
    assert payload["summary"] == (
        "RepoGuard review\n"
        "Conclusion: failure\n"
        "Findings: 4\n"
        "Highest severity: critical\n"
        "Annotations: 3\n"
        "Omitted annotations: 1"
    )
    rendered = "\n".join(
        f"{annotation['title']}\n{annotation['message']}" for annotation in annotations
    )
    assert all(token not in rendered for token in ("@", "<", ">", "[", "]", "`", "*"))
    assert "&#64;" not in rendered
    assert "\uff20octocat" in rendered
    assert len(cast(str, annotations[0]["title"]).encode("utf-8")) <= 255
    assert cast(str, annotations[0]["title"]).endswith("&#8230;")
    assert "octocat" in rendered


def test_check_builder_caps_annotations_and_reports_exact_omitted_count() -> None:
    references = tuple(
        _reference(
            path="src/generated.py",
            start_line=line,
            end_line=line,
            target=None,
        )
        for line in range(1, 1_002)
    )
    finding = _finding(
        severity=FindingSeverity.LOW,
        references=references,
        source=FindingSource.AGENT,
    )

    proposal = _check_proposal(review=_review(findings=(finding,)))
    payload = proposal.payload
    annotations = cast(list[dict[str, object]], payload["annotations"])

    assert len(annotations) == 1_000
    assert annotations[0]["start_line"] == 1
    assert annotations[-1]["start_line"] == 1_000
    assert payload["omitted_count"] == 1
    assert cast(str, payload["summary"]).endswith("Omitted annotations: 1")


