def _fixed_commit_oid(tree_oid: str = _TREE_OID, head_oid: str = _HEAD_OID) -> str:
    identity = f"{REPAIR_PUBLICATION_AUTHOR_NAME} <{REPAIR_PUBLICATION_AUTHOR_EMAIL}> 0 +0000"
    commit = (
        f"tree {tree_oid}\n"
        f"parent {head_oid}\n"
        f"author {identity}\n"
        f"committer {identity}\n"
        "\n"
        f"{REPAIR_PUBLICATION_COMMIT_MESSAGE}"
    ).encode()
    header = f"commit {len(commit)}\0".encode("ascii")
    return hashlib.sha1(header + commit, usedforsecurity=False).hexdigest()


_COMMIT_OID = _fixed_commit_oid()


def _reference(
    *,
    path: str = "src/app.py",
    side: EvidenceSide = EvidenceSide.NEW,
    start_line: int | None = 7,
    end_line: int | None = 7,
    target: str | None = "c" * 64,
) -> ProductReference:
    return ProductReference(path, side, _HEAD_OID, start_line, end_line, target)


def _finding(
    *,
    severity: FindingSeverity = FindingSeverity.HIGH,
    title: str = "Unsafe change",
    message: str = "Review this exact line.",
    remediation: str = "Use the safe API.",
    references: tuple[ProductReference, ...] | None = None,
    source: FindingSource = FindingSource.DETERMINISTIC,
) -> ProductFinding:
    return ProductFinding(
        source=source,
        rule_id="agent_reasoning" if source is FindingSource.AGENT else "private_key_material",
        category=FindingCategory.SECURITY,
        severity=severity,
        title=title,
        message=message,
        remediation=remediation,
        references=references
        or (_reference(target=None if source is FindingSource.AGENT else "c" * 64),),
    )


def _review(
    *,
    findings: tuple[ProductFinding, ...] = (),
    base_ref: str = "main",
    head_oid: str = _HEAD_OID,
    review_sha256: str = _REVIEW_SHA256,
) -> ProductReviewResult:
    severity_order = {
        FindingSeverity.INFO: 0,
        FindingSeverity.LOW: 1,
        FindingSeverity.MEDIUM: 2,
        FindingSeverity.HIGH: 3,
        FindingSeverity.CRITICAL: 4,
    }
    highest = (
        None
        if not findings
        else max((finding.severity for finding in findings), key=severity_order.__getitem__)
    )
    conclusion = (
        ProductConclusion.FAILURE
        if highest in {FindingSeverity.HIGH, FindingSeverity.CRITICAL}
        else ProductConclusion.SUCCESS
    )
    return ProductReviewResult(
        schema_version=1,
        repository_alias="repository",
        object_format="sha1",
        base_ref=base_ref,
        head_ref="feature",
        base_oid=_BASE_OID,
        head_oid=head_oid,
        merge_base_oid=_BASE_OID,
        review_profile="deterministic",
        provider=None,
        model=None,
        evidence_sha256="d" * 64,
        deterministic_review_sha256="e" * 64,
        review_sha256=review_sha256,
        findings=findings,
        finding_count=len(findings),
        highest_severity=highest,
        conclusion=conclusion,
    )


def _validated_repair(
    *,
    commit_oid: str = _COMMIT_OID,
) -> tuple[RepairSnapshot, RepairPreview]:
    prompt = RepairPromptIdentity(
        "repoguard_repair",
        1,
        "1" * 64,
        "2" * 64,
        "3" * 64,
    )
    context = RepairContextSummary(
        RepairContextOutcome.NOT_REQUESTED,
        None,
        None,
        0,
        0,
        0,
        None,
        None,
    )
    candidate = RepairCandidate(
        1,
        _CANDIDATE_ID,
        _REQUEST_SHA256,
        prompt,
        context,
        "4" * 64,
        _TREE_OID,
        commit_oid,
        ("src/app.py",),
        1,
        0,
        0,
        0,
    )
    command = ValidationCommandResult(
        0,
        0,
        None,
        False,
        1,
        "5" * 64,
        0,
        False,
        "6" * 64,
        0,
        False,
    )
    validation = RepairValidation(
        1,
        _VALIDATION_SHA256,
        _CANDIDATE_ID,
        "7" * 64,
        "8" * 64,
        f"sha256:{'9' * 64}",
        1,
        2,
        True,
        None,
        (command,),
        1,
        False,
        0,
        1,
        1,
        True,
    )
    snapshot = RepairSnapshot(
        1,
        _SESSION_ID,
        RepairState.VALIDATED,
        _REQUEST_SHA256,
        1,
        2,
        1,
        ("src/app.py",),
        candidate,
        validation,
        None,
        None,
        None,
        None,
        False,
    )
    preview = RepairPreview(
        1,
        _SESSION_ID,
        RepairState.VALIDATED,
        _CANDIDATE_ID,
        _VALIDATION_SHA256,
        ("src/app.py",),
        "diff --git a/src/app.py b/src/app.py\n",
        REPAIR_APPROVAL_CONFIRMATION,
    )
    return snapshot, preview


def _check_proposal(
    *,
    review: ProductReviewResult | None = None,
    repository_id: int = 123456,
    repository_full_name: str = "owner/repository",
    policy_sha256: str = _POLICY_SHA256,
) -> GitHubProposal:
    return build_github_check_proposal(
        repository_id=repository_id,
        repository_full_name=repository_full_name,
        pull_request_number=7,
        base_ref="main",
        origin=GitHubProposalOrigin.CLI,
        review_result=_review() if review is None else review,
        policy_sha256=policy_sha256,
        created_at_us=1_000_000,
    )


def _repair_proposal(
    *,
    review: ProductReviewResult | None = None,
    snapshot: RepairSnapshot | None = None,
    preview: RepairPreview | None = None,
) -> GitHubProposal:
    default_snapshot, default_preview = _validated_repair()
    return build_github_repair_proposal(
        repository_id=123456,
        repository_full_name="owner/repository",
        pull_request_number=7,
        base_ref="main",
        origin=GitHubProposalOrigin.CLI,
        review_result=_review() if review is None else review,
        profile_name="safe",
        snapshot=default_snapshot if snapshot is None else snapshot,
        preview=default_preview if preview is None else preview,
        created_at_us=1_000_000,
    )


def _check_payload() -> dict[str, object]:
    return cast(dict[str, object], _check_proposal().payload)


def _repair_payload() -> dict[str, object]:
    return cast(dict[str, object], _repair_proposal().payload)


def _proposal(kind: GitHubProposalKind = GitHubProposalKind.CHECK) -> GitHubProposal:
    return _check_proposal() if kind is GitHubProposalKind.CHECK else _repair_proposal()


